#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '../../../..');
const cache = path.join(root, 'data/math-parser-build/js');
fs.mkdirSync(cache, { recursive: true });
for (const file of ['package.json', 'package-lock.json']) {
  fs.copyFileSync(path.join(__dirname, file), path.join(cache, file));
}
const result = spawnSync('npm', ['ci', '--ignore-scripts', '--no-audit', '--no-fund'], { cwd: cache, stdio: 'inherit' });
if (result.status !== 0) throw new Error('Math parser build dependencies failed to install');
const built = require(path.join(cache, 'node_modules/esbuild')).buildSync({
  entryPoints: [path.join(__dirname, 'index.mjs')],
  outfile: path.join(__dirname, '../math-parser.js'),
  nodePaths: [path.join(cache, 'node_modules')],
  bundle: true, format: 'iife', platform: 'neutral', mainFields: ['module', 'main'],
  conditions: ['module'], target: 'es2020', minify: true, legalComments: 'inline', metafile: true,
});
const packages = new Map();
for (const input of Object.keys(built.metafile.inputs)) {
  if (!input.includes('node_modules/')) continue;
  let dir = path.dirname(path.resolve(input));
  while (!fs.existsSync(path.join(dir, 'package.json'))) dir = path.dirname(dir);
  const meta = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const license = fs.readdirSync(dir).find(file => /^licen[sc]e(?:\..*)?$/i.test(file));
  if (!license) throw new Error(`Missing license for ${meta.name}`);
  packages.set(meta.name, `${meta.name}@${meta.version}\n${fs.readFileSync(path.join(dir, license), 'utf8')}`);
}
const licenses = [...packages.entries()].sort(([a], [b]) => a.localeCompare(b))
  .map(([, license]) => license).join('\n\n');
const artifact = path.join(__dirname, '../math-parser.js');
fs.writeFileSync(artifact, '/* Generated by math-parser/build.cjs. Third-party notices:\n'
  + licenses.replaceAll('*/', '* /') + '\n*/\n' + fs.readFileSync(artifact, 'utf8'));
